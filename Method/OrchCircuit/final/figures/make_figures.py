def table(after, ncols):
    lines = MD.split('\n'); i = next(k for k, l in enumerate(lines) if l.startswith(after)); rows = []
    for l in lines[i + 1:]:
        if l.startswith('#'):
            break
        if l.startswith('| '):
            c = [x.strip() for x in l.strip().strip('|').split('|')]
            if len(c) == ncols and not all(re.fullmatch(r':?-+:?', x) for x in c):
                rows.append(c)
    return rows[1:]


num = lambda s: float(re.sub(r'[^0-9.\-]', '', s.replace('−', '-')))


def err_coords(pts):  # pts: list of (x, y, lo, hi)
    return ' '.join(f'({x},{f2(y)}) += (0,{f2(hi - y)}) -= (0,{f2(y - lo)})' for x, y, lo, hi in pts)


def plain(pts):
    return ' '.join(f'({x},{f2(y)})' for x, y in pts)


def axis(opts, body):
    # every symbolic axis gets its full tick list (xtick=data only ticks the first plot's points),
    # and dashed reference lines are drawn as plain lines even inside bar charts
    opts = re.sub(r'symbolic x coords=\{([^}]*)\}, xtick=data', lambda m: 'symbolic x coords={%s}, xtick={%s}' % (m.group(1), m.group(1)), opts)
    body = body.replace('\\addplot[black,dashed,line width=0.3pt,forget plot]', '\\addplot[black,dashed,line width=0.3pt,forget plot,sharp plot]')
    return '\\begin{tikzpicture}\\begin{axis}[nmi, ' + opts + ']' + body + '\\end{axis}\\end{tikzpicture}'


def panel(tikz, cap, lab):
    return f'\\nmipanel{{{tikz}}}{{{cap}}}{{{lab[-1]}}}'


def ptsplot(color, mark, pts, shift='0pt', extra=''):
    return (f'\\addplot[only marks,mark={mark},mark size=1.1pt,color={color},xshift={shift},{extra}error bars/.cd,y dir=both,y explicit,'
            f'error bar style={{line width=0.3pt}}] coordinates {{{err_coords(pts)}}};')


def bars(color, pts, extra=''):
    return f'\\addplot[fill={color},draw=none,{extra}] coordinates {{{plain(pts)}}};'


def zero(xs):
    return f'\\addplot[black,dashed,line width=0.3pt,forget plot] coordinates {{({xs[0]},0) ({xs[-1]},0)}};'


